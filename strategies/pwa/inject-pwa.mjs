import { writeFile, mkdir, readFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { logger } from '../../core/logger.mjs';

const SW_CONTENT = `/* Generated by rewriter – offline-capable service worker */
const CACHE = 'rewriter-pwa-v1';
const ASSETS = self.__PRECACHE || ['/', '/index.html', '/manifest.webmanifest'];

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request).then((cached) => {
      const fetched = fetch(e.request).then((res) => {
        if (res && res.status === 200 && res.type === 'basic') {
          const clone = res.clone();
          caches.open(CACHE).then((c) => c.put(e.request, clone));
        }
        return res;
      }).catch(() => cached);
      return cached || fetched;
    })
  );
});
`;

const MANIFEST = {
  name: 'Converted PWA',
  short_name: 'PWA',
  start_url: '.',
  display: 'standalone',
  background_color: '#ffffff',
  theme_color: '#0f172a',
  icons: [
    {
      src: 'icon-192.png',
      sizes: '192x192',
      type: 'image/png',
      purpose: 'any maskable',
    },
    {
      src: 'icon-512.png',
      sizes: '512x512',
      type: 'image/png',
      purpose: 'any maskable',
    },
  ],
};

/**
 * Inject basic PWA support into a static dist/ or source root.
 * Works on already-built output or on source that will be built later.
 */
export async function injectPwa(targetDir, options = {}) {
  const changes = [];
  const name = options.name || 'Converted App';
  const shortName = options.shortName || 'App';

  // Write service worker
  const swPath = path.join(targetDir, 'sw.js');
  await writeFile(swPath, SW_CONTENT, 'utf8');
  changes.push({ file: 'sw.js', action: 'create' });

  // Write manifest
  const manifest = { ...MANIFEST, name, short_name: shortName };
  const manifestPath = path.join(targetDir, 'manifest.webmanifest');
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2), 'utf8');
  changes.push({ file: 'manifest.webmanifest', action: 'create' });

  // Ensure icons exist (minimal 1x1 png placeholders are better than broken refs)
  // We write tiny valid PNGs later if needed; for now reference them.
  // Register SW + link manifest in index.html if present
  const indexCandidates = [
    path.join(targetDir, 'index.html'),
    path.join(targetDir, 'public', 'index.html'),
  ];

  for (const idx of indexCandidates) {
    try {
      let html = await readFile(idx, 'utf8');
      let modified = false;

      if (!html.includes('manifest.webmanifest')) {
        html = html.replace(
          /<\/head>/i,
          `  <link rel="manifest" href="./manifest.webmanifest" />\n  <meta name="theme-color" content="#0f172a" />\n</head>`
        );
        modified = true;
      }
      if (!html.includes('serviceWorker') && !html.includes('sw.js')) {
        html = html.replace(
          /<\/body>/i,
          `  <script>
    if ('serviceWorker' in navigator) {
      window.addEventListener('load', () => {
        navigator.serviceWorker.register('./sw.js').catch(console.warn);
      });
    }
  </script>\n</body>`
        );
        modified = true;
      }
      if (modified) {
        await writeFile(idx, html, 'utf8');
        changes.push({ file: path.relative(targetDir, idx), action: 'patch-html' });
      }
      break;
    } catch {
      // try next
    }
  }

  logger.info(`PWA injected (${changes.length} changes)`);
  return { ok: true, changes, strategy: 'inject-pwa' };
}
